"""Merge data/<year>/weekNN.json into questions.js (hardcoded question bank for the site).

Each year folder is one run of the course. A weekly file may carry a "label" (e.g. "7A", "7B")
when a week has more than one assignment set.
"""
import glob, json, pathlib, re

root = pathlib.Path(__file__).parent
CURRENT = "2026"
RUN_INFO = {
    "2026": "Jul–Oct 2026 · this run",
    "2025": "Jul–Oct 2025",
    "2024": "Jul–Oct 2024",
    "2023": "Jul–Oct 2023",
}

def norm(s):
    return re.sub(r"[^a-z0-9]+", "", s.lower())

bank, runs = [], []
for run_dir in sorted((p for p in (root / "data").iterdir() if p.is_dir()), key=lambda p: p.name, reverse=True):
    run = run_dir.name
    count = 0
    for f in sorted(glob.glob(str(run_dir / "week*.json"))):
        d = json.load(open(f, encoding="utf-8"))
        wk = d.get("label", str(d["week"]))
        for n, q in enumerate(d["questions"], 1):
            assert q["options"] and q["answer"], f"{f} Q{n}"
            assert all(0 <= a < len(q["options"]) for a in q["answer"]), f"{f} Q{n} bad answer index"
            # this run keeps its original ids so saved progress survives
            qid = f"w{wk}q{n}" if run == CURRENT else f"r{run}w{wk}q{n}"
            item = {"id": qid, "run": run, "week": wk, "wn": d["week"], "n": n, "q": q["q"],
                    "options": q["options"], "answer": q["answer"], "explanation": q["explanation"]}
            if q.get("flag"):
                item["note"] = q["flag"]
            bank.append(item)
            count += 1
    if count:
        runs.append({"id": run, "label": RUN_INFO.get(run, run), "count": count})

# A question "repeats" when the same stem + correct answer appears in more than one run
groups = {}
for q in bank:
    g = norm(q["q"]) + "|" + "|".join(sorted(norm(q["options"][a]) for a in q["answer"]))
    groups.setdefault(g, []).append(q)
for i, qs in enumerate(groups.values()):
    years = sorted({q["run"] for q in qs}, reverse=True)
    if len(years) > 1:
        for q in qs:
            q["rep"] = years
            q["grp"] = i

js = ("// Generated by build.py from data/<year>/*.json — do not edit by hand.\n"
      "window.RUNS = " + json.dumps(runs, ensure_ascii=False) + ";\n"
      "window.QUESTIONS = " + json.dumps(bank, ensure_ascii=False, separators=(",", ":")) + ";\n")
(root / "questions.js").write_text(js, encoding="utf-8")
reps = len({q["grp"] for q in bank if "grp" in q})
print(f"{len(bank)} questions · runs: " + ", ".join(f"{r['id']}={r['count']}" for r in runs) + f" · {reps} repeated groups")
