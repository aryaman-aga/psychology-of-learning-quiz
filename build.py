"""Merge data/weekNN.json into questions.js (hardcoded question bank for the site)."""
import glob, json, pathlib

root = pathlib.Path(__file__).parent
bank = []
for f in sorted(glob.glob(str(root / "data" / "week*.json"))):
    d = json.load(open(f, encoding="utf-8"))
    for n, q in enumerate(d["questions"], 1):
        assert q["options"] and q["answer"], f"{f} Q{n}"
        assert all(0 <= a < len(q["options"]) for a in q["answer"]), f"{f} Q{n} bad answer index"
        item = {"id": f"w{d['week']}q{n}", "week": d["week"], "n": n, "q": q["q"],
                "options": q["options"], "answer": q["answer"], "explanation": q["explanation"]}
        if q.get("flag"):
            item["note"] = q["flag"]
        bank.append(item)

js = "// Generated by build.py from data/*.json — do not edit by hand.\nwindow.QUESTIONS = " + json.dumps(bank, ensure_ascii=False, indent=1) + ";\n"
(root / "questions.js").write_text(js, encoding="utf-8")
print(f"{len(bank)} questions across {len({q['week'] for q in bank})} weeks")
